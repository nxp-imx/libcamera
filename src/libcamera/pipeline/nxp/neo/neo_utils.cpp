/**
 * \struct CameraProperties
 * \brief Camera properties defined by configuration file
 *
 * This structure reports to the pipeline handler a set of properties coming
 * from the platform configuration file.
 *
 * \var CameraProperties::image1Stream
 * \brief Camera has an image1 stream for HDR or RGBIr context switch mode
 *
 * \var CameraProperties::eDataStream
 * \brief Camera has a dedicated stream for embedded data
 *
 * \var CameraProperties::rgbirCfa
 * \brief Camera sensor uses an RGBIr color filter array
 *
 * This parameter indicates whether the camera sensor has an RGBIr (RGB + Infrared)
 * color filter array instead of a standard Bayer pattern.
 *
 * \var CameraProperties::formatBpp
 * \brief Format bit-per-pixel filter value (optional)
 *
 * This parameter restricts the camera formats exposed to the user to the subset
 * of formats whose mbus-code bit-per-pixel matches this value.
 *
 * \var CameraProperties::formatSize
 * \brief Camera format size filter value (optional)
 *
 * This parameter restricts the camera formats exposed to the user to the subset
 * of formats whose size matches this value.
 *
 * \var CameraProperties::orientation
 * \brief Camera orientation (optional)
 *
 * This parameter defines the preferred orientation to be used for the camera
 * streams. Range of values is the subset of orientations defined by the
 * Orientation enum class, relevant to the ones achievable with a combination of
 * horizontal and vertical flips:
 * Rotate0 (1), Rotate0Mirror (2), Rotate180 (3), Rotate180Mirror (4)
 *
 * \var CameraProperties::controlsDelay
 * \brief Delay to update the controls on front-end frame done event (optional)
 *
 * Camera controls update is synchronized on the front-end frame done events.
 * For cameras having issue with that timing, this allows delaying the controls
 * update by a user configured delay.
 *
 * \var CameraProperties::vividInstances
 * \brief Configuration for vivid virtual video device instances (optional)
 *
 * This parameter is optional as only relevant to the specific case where
 * vivid instance(s) are used by a virtual camera for testing purposes. It
 * configures each vivid instances configuration for that camera. Each instance
 * corresponds to a camera stream and specifies its pixel format, size, loopback
 * mode, and test pattern generator settings.
 */

/**
 * \struct CameraProperties::VividConfig
 * \brief Configuration for a vivid virtual video device instance
 *
 * This structure defines the configuration parameters for a vivid (Virtual
 * Video Test Driver) device instance used for testing purposes.
 *
 * \var CameraProperties::VividConfig::pixelFormat
 * \brief Pixel format for the vivid device
 *
 * \var CameraProperties::VividConfig::size
 * \brief Frame size for the vivid device
 *
 * \var CameraProperties::VividConfig::loopback
 * \brief Enable loopback mode for the vivid device
 *
 * When enabled, the vivid device operates in loopback mode where the video
 * frames of the output devices are looped back to the input (capture). Doing
 * so, the Test Pattern Generator is unused.
 *
 * \var CameraProperties::VividConfig::tpgPattern
 * \brief Test pattern generator pattern selection
 *
 * Selects the test pattern to be generated by the vivid device. Valid values
 * are integer in the [0..20] range.
 * See also vivid-ctrls.c tpg_pattern enum.
 *
 * \var CameraProperties::VividConfig::tpgHorizontalMovement
 * \brief Test pattern generator horizontal movement setting
 *
 * Controls the horizontal movement of the test pattern. Valid values are
 * integer in the [0..6] range, where 3 corresponds to "No Movement".
 * See also vivid-ctrls.c tpg_move_mode enum.
 *
 * \var CameraProperties::VividConfig::tpgVerticalMovement
 * \brief Test pattern generator vertical movement setting
 *
 * Controls the vertical movement of the test pattern. Valid values are
 * integer in the [0..6] range, where 3 corresponds to "No Movement".
 * See also vivid-ctrls.c tpg_move_mode enum.
 */

